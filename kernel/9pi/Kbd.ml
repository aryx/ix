(* the external scan codes' state (kbscans[KbExt]) *)
type kbscan = {
  mutable esc1 : bool;
  mutable esc2 : int;
  mutable kshift : bool;
  mutable kaltgr : bool;
  mutable kctl : bool;
  mutable kcaps : bool;
  mutable kalt : bool;
  mutable knum : bool;
  mutable collecting : bool;
  mutable kc : int list;
  mutable buttons : int;
}

let ks = { esc1 = false; esc2 = 0; kshift = false; kaltgr = false; kctl = false; kcaps = false; kalt = false;
           knum = false; collecting = false; kc = []; buttons = 0 }

let kbdmouse = ref (fun (_ : int) -> ())

let kdebug = ref false

let kbdputsc k =
  if k = 0xe0 then ks.esc1 <- true
  else if k = 0xe1 then ks.esc2 <- 2
  else begin
    let keyup = k land 0x80 <> 0 and code = k land 0x7f in
    let c =
      if ks.esc1 then begin ks.esc1 <- false; Some kbtabesc1.(code) end
      else if ks.esc2 > 0 then begin ks.esc2 <- ks.esc2 - 1; None end
      else if ks.kshift then Some kbtabshift.(code)
      else if ks.kaltgr then Some kbtabaltgr.(code)
      else if ks.kctl then Some kbtabctrl.(code)
      else Some kbtab.(code) in
    match c with
    | None -> ()
    | Some c ->
        let c = if ks.kcaps && c >= Char.code 'a' && c <= Char.code 'z' then c + Char.code 'A' - Char.code 'a' else c in
        if keyup then begin
          (* a release matters for the shifts only *)
          if c = ctrl then ks.kctl <- false
          else if c = alt then ks.kalt <- false
          else if c = altgr then ks.kaltgr <- false
          else if c = shift then ks.kshift <- false
          else if c > kmouse && c <= kmouse + 5 then begin
            ks.buttons <- ks.buttons land lnot (1 lsl (c - kmouse - 1));
            !kbdmouse ks.buttons
          end
        end
        else if c land (spec lor kf) = 0 then begin
          (* a character; Ctl-Alt-Del would reboot *)
          if ks.collecting then begin
            (* latin1: not here, the characters given as they are *)
            ks.kc <- ks.kc @ [ c ];
            List.iter Devcons.kbdputc ks.kc;
            ks.kc <- [];
            ks.collecting <- false
          end
          else Devcons.kbdputc c
        end
        else if c = ctrl then ks.kctl <- true
        else if c = alt then begin
          ks.kalt <- true;
          (* ctl-alt (a VM's grab) starts no compose sequence *)
          if not ks.kctl then begin ks.collecting <- true; ks.kc <- [] end
        end
        else if c = altgr then ks.kaltgr <- true
        else if c = shift then ks.kshift <- true
        else if c = caps then ks.kcaps <- not ks.kcaps
        else if c = num then ks.knum <- not ks.knum
        else if c > kmouse && c <= kmouse + 5 then begin
          ks.buttons <- ks.buttons lor (1 lsl (c - kmouse - 1));
          !kbdmouse ks.buttons
        end
        else if c = kf lor 11 then begin
          Devcons.print "kbd debug on, F12 turns it off\n";
          kdebug := true;
          Devcons.kbdputc c
        end
        else if c = kf lor 12 then begin kdebug := false; Devcons.kbdputc c end
        else Devcons.kbdputc c
  end
